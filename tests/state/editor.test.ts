import { describe, expect, it } from 'vitest';
import { createWorkspace, queries } from '../../src/app/workspace';
import { activeCombos, allCombos, handClasses, policyStats } from '../../src/modules/study/domain';
import type { WorkspaceSnapshot } from '../../src/modules/study/domain';
import { btnRange, bbRange } from '../../src/fixtures/s01';
import { createMockSolver } from '../../src/mocks/solver';
import { snapshotSchema } from '../../src/persistence/schema';

async function setup(initial: WorkspaceSnapshot | null = null) {
  let saved = initial;
  const repository = { async load() { return saved ? structuredClone(saved) : null; }, async save(data: WorkspaceSnapshot) { saved = structuredClone(data); } };
  const app = createWorkspace(repository, createMockSolver(0));
  await app.commands.initialize();
  const result = app.commands.createCase();
  if (!result.ok) throw new Error(result.message);
  const id = result.value;
  return { ...app, id, repository, current: () => app.store.getState().data.cases[id], read: () => saved };
}
const x = { check: 10000, bet33: 0, bet75: 0 };
const mix = { check: 2500, bet33: 5000, bet75: 2500 };

describe('D02 edit transactions', () => {
  it('undoes condition and name changes as a single transaction', async () => {
    const app = await setup();
    const before = structuredClone(app.current());
    app.commands.reviseSpot(app.id, { ...before.spot, potMinor: 650 }, '改变底池');
    app.commands.undo(app.id);
    expect(app.current().spot).toEqual(before.spot);
    expect(app.current().spotRevisionId).toBe(before.spotRevisionId);
    expect(app.current().name).toBe(before.name);
    app.commands.redo(app.id);
    expect(app.current().name).toBe('改变底池');
    expect(app.current().spot.potMinor).toBe(650);
  });
  it('skips locked combinations in every bulk path and records a batch as one undo entry', async () => {
    const app = await setup();
    const ids = activeCombos(app.current().spot, btnRange).filter(combo => combo.startsWith('A'));
    const first = ids[0];
    app.commands.editPolicy(app.id, [first], mix, 0);
    app.commands.setLocks(app.id, [first], true, 1);
    const before = structuredClone(app.current().draft);
    app.commands.editPolicy(app.id, ids, x, 2);
    expect(app.current().draft.choices[first]).toEqual(mix);
    expect(app.current().draft.choices[ids[1]]).toEqual(x);
    expect(app.current().editHistory?.past).toHaveLength(3);
    app.commands.undo(app.id);
    expect(app.current().draft.choices).toEqual(before.choices);
    expect(app.current().draft.lockedCombos).toEqual(before.lockedCombos);
    app.commands.redo(app.id);
    expect(app.current().draft.choices[ids[1]]).toEqual(x);
    app.commands.loadExample(app.id);
    expect(app.current().draft.choices[first]).toEqual(mix);
    app.commands.clearDraft(app.id);
    expect(Object.keys(app.current().draft.choices)).toEqual([first]);
    app.commands.fillRemaining(app.id);
    expect(app.current().draft.choices[first]).toEqual(mix);
    await app.commands.requestReference(app.id);
    app.commands.clearDraft(app.id);
    app.commands.fillFromReference(app.id, app.current().jobs[0].id, app.current().draft.editRevision);
    expect(app.current().draft.choices[first]).toEqual(mix);
    const plan = app.commands.saveHeroPlan(app.id, { combo: first, action: 'check', opponentBranch: 'turn-check', response: 'reassess', reason: '', turnPlan: '' }, app.current().spotRevisionId);
    if (!plan.ok) throw new Error(plan.message);
    expect(app.commands.applyHeroAction(app.id, plan.value, 'hero', app.current().draft.editRevision).ok).toBe(false);
  });
  it('allows partial drafts, rejects submission and stale edits, and drops redo after a new edit', async () => {
    const app = await setup();
    app.commands.fillRemaining(app.id);
    const combo = activeCombos(app.current().spot, btnRange)[0];
    const rev = app.current().draft.editRevision;
    app.commands.editPolicy(app.id, [combo], { ...x, check: 5000 }, rev);
    expect(app.commands.submitPolicy(app.id).ok).toBe(false);
    expect(app.commands.editPolicy(app.id, [combo], mix, rev).ok).toBe(false);
    expect(app.current().draft.choices[combo].check).toBe(5000);
    app.commands.undo(app.id);
    app.commands.editPolicy(app.id, [combo], mix, app.current().draft.editRevision);
    expect(app.current().editHistory?.future).toHaveLength(0);
    expect(app.commands.redo(app.id).ok).toBe(false);
    app.commands.setPendingInput(true);
    expect(app.commands.submitPolicy(app.id).ok).toBe(false);
    expect(app.current().versions).toHaveLength(0);
    app.commands.setPendingInput(false);
    expect(app.commands.submitPolicy(app.id).ok).toBe(true);
  });
  it('stores at most 30 reversible transactions and persists locks, history and input snapshots', async () => {
    const app = await setup();
    const combo = activeCombos(app.current().spot, btnRange)[0];
    for (let i = 0; i < 35; i++) app.commands.editPolicy(app.id, [combo], i % 2 ? mix : x, app.current().draft.editRevision);
    app.commands.setLocks(app.id, [combo], true, app.current().draft.editRevision);
    expect(app.current().editHistory?.past).toHaveLength(30);
    await app.commands.flushSaves();
    const parsed = snapshotSchema.parse(app.read());
    expect(parsed.cases[app.id].draft.lockedCombos).toEqual([combo]);
    expect(parsed.cases[app.id].editHistory?.past).toHaveLength(30);
    const restored = createWorkspace(app.repository, createMockSolver(0));
    await restored.commands.initialize();
    restored.commands.undo(app.id);
    expect(restored.store.getState().data.cases[app.id].draft.lockedCombos).toEqual([]);
  });
});

describe('D02 range revisions and immutable versions', () => {
  it('creates an explicitly assisted two-version example with two bound synthetic reports', async () => {
    const app = await setup();
    const result = await app.commands.createComparisonExample();
    if (!result.ok) throw new Error(result.message);
    const c = app.store.getState().data.cases[result.value];
    expect(c.versions).toHaveLength(2);
    expect(c.reports).toHaveLength(2);
    expect(c.versions.every(v => v.assistance === 'example')).toBe(true);
    expect(c.reports.map(r => r.policyRevisionId)).toEqual(c.versions.map(v => v.id));
    expect(c.reports.map(r => r.sampleEv?.template)).toEqual(['reference', 'check']);
    expect(c.reports.every(r => r.dataKind === 'synthetic')).toBe(true);
    expect(app.current().versions).toHaveLength(0);
  });
  it('separates input weights from action probabilities and handles add, exclude, dead cards and zero mass', async () => {
    const app = await setup();
    app.commands.fillRemaining(app.id);
    const combo = activeCombos(app.current().spot, btnRange)[0];
    const other = activeCombos(app.current().spot, btnRange)[1];
    app.commands.editPolicy(app.id, [combo], mix, app.current().draft.editRevision);
    app.commands.reviseRange(app.id, 'BTN', [combo], 1000, app.current().draft.editRevision);
    expect(app.current().draft.choices[combo]).toEqual(mix);
    const stats = queries.stats(app.current());
    expect(stats.totals.bet33).toBeCloseTo(500 / stats.mass);
    const oldRevision = app.current().spotRevisionId;
    app.commands.reviseRange(app.id, 'BTN', [combo], 0, app.current().draft.editRevision);
    expect(queries.stats(app.current()).combos).not.toContain(combo);
    expect(app.current().draft.choices[combo]).toBeUndefined();
    app.commands.undo(app.id);
    expect(app.current().spotRevisionId).toBe(oldRevision);
    expect(app.current().draft.choices[combo]).toEqual(mix);
    const inactive = allCombos.find(c => btnRange[c] === 0 && !app.current().spot.board.some(card => c.includes(card)))!;
    app.commands.reviseRange(app.id, 'BTN', [inactive], 10000, app.current().draft.editRevision);
    expect(queries.stats(app.current()).missing).toBe(1);
    expect(app.current().draft.choices[inactive]).toBeUndefined();
    const dead = handClasses[0].combos.find(c => c.includes('As'))!;
    expect(app.commands.reviseRange(app.id, 'BTN', [dead], 10000, app.current().draft.editRevision).ok).toBe(false);
    const ids = activeCombos(app.current().spot, queries.weights('BTN', app.current()));
    app.commands.reviseRange(app.id, 'BTN', ids, 0, app.current().draft.editRevision);
    expect(queries.stats(app.current()).totals).toEqual({ check: 0, bet33: 0, bet75: 0 });
    expect(queries.stats(app.current()).mass).toBe(0);
    expect(app.commands.submitPolicy(app.id).ok).toBe(false);
    expect(policyStats(app.current().spot, queries.weights('BTN', app.current()), app.current().draft.choices).combos).not.toContain(other);
  });
  it('binds two reports to fixed ranges, restores V1 as V3 and forks without rewriting evidence', async () => {
    const app = await setup();
    app.commands.fillRemaining(app.id);
    const v1 = app.commands.submitPolicy(app.id);
    if (!v1.ok) throw new Error(v1.message);
    await app.commands.requestSolve(app.id, v1.value);
    const combo = activeCombos(app.current().spot, btnRange)[0];
    app.commands.editPolicy(app.id, [combo], mix, app.current().draft.editRevision);
    const v2 = app.commands.submitPolicy(app.id);
    if (!v2.ok) throw new Error(v2.message);
    await app.commands.requestSolve(app.id, v2.value);
    const evidence = structuredClone({ versions: app.current().versions, reports: app.current().reports });
    app.commands.reviseRange(app.id, 'BTN', [combo], 0, app.current().draft.editRevision);
    await app.commands.requestSolve(app.id, v1.value);
    expect(app.current().jobs.at(-1)?.result?.availability).toBe('available');
    app.commands.restoreAsDraft(app.id, v1.value);
    expect(app.current().draft.restoredFrom).toBe(v1.value);
    const v3 = app.commands.submitPolicy(app.id);
    expect(v3.ok).toBe(true);
    expect(app.current().versions).toHaveLength(3);
    expect(app.current().versions.slice(0, 2)).toEqual(evidence.versions);
    expect(app.current().reports.slice(0, 2)).toEqual(evidence.reports);
    const branch = app.commands.forkVersion(app.id, v2.value, '低频下注实验');
    if (!branch.ok) throw new Error(branch.message);
    const fork = app.store.getState().data.cases[branch.value];
    expect(fork.branchSource?.versionId).toBe(v2.value);
    expect(fork.draft.choices).toEqual(evidence.versions[1].choices);
    expect(fork.reports).toEqual([]);
    app.commands.clearDraft(branch.value);
    expect(app.current().versions.slice(0, 2)).toEqual(evidence.versions);
  });
  it('invalidates fixture matching and fingerprints for changed BTN or BB inputs while retaining old reports', async () => {
    const app = await setup();
    await app.commands.requestReference(app.id);
    const original = structuredClone(app.current().jobs[0]);
    const combo = activeCombos(app.current().spot, bbRange)[0];
    app.commands.reviseRange(app.id, 'BB', [combo], bbRange[combo] === 5000 ? 7500 : 5000, app.current().draft.editRevision);
    expect(queries.latestReference(app.current())).toBeUndefined();
    await app.commands.requestReference(app.id);
    expect(app.current().jobs[1].result?.availability).toBe('uncovered');
    expect(app.current().jobs[1].result?.inputFingerprint).not.toBe(original.result?.inputFingerprint);
    expect(app.commands.fillFromReference(app.id, original.id, app.current().draft.editRevision).ok).toBe(false);
    expect(app.commands.loadExample(app.id).ok).toBe(false);
    app.commands.undo(app.id);
    expect(queries.latestReference(app.current())?.id).toBe(original.id);
    expect(app.current().jobs[0]).toEqual(original);
  });
  it('loads pre-D02 records additively without losing previous Hero plans or reports', async () => {
    const app = await setup();
    const legacy = snapshotSchema.parse(app.store.getState().data);
    expect(legacy.cases[app.id].draft.lockedCombos).toEqual([]);
    expect(legacy.cases[app.id].ranges).toBeUndefined();
    expect(queries.weights('BTN', legacy.cases[app.id])).toEqual(btnRange);
  });
});
