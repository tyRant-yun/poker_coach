import { test, expect } from '@playwright/test';
import { mkdir, readFile } from 'node:fs/promises';

test.beforeAll(async () => { await mkdir('.artifacts/hero', { recursive: true }); });

test('Hero-first: plan one hand, read the entire recommendation, and preserve the hand when assisting the range', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/library');
  await page.getByRole('button', { name: '创建研究案例' }).click();
  await page.getByRole('tab', { name: /Hero 推演/ }).click();
  await expect(page.getByRole('tab', { name: /Hero 推演/ })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('combobox', { name: 'Hero 具体组合' }).selectOption('AdKd');
  await page.getByRole('group', { name: 'Hero 翻牌行动' }).getByRole('button', { name: '下注 33%', exact: true }).click();
  await page.getByRole('textbox', { name: 'Hero 行动理由' }).fill('先检查这手牌，再联系整个范围。');
  await page.getByRole('textbox', { name: 'Hero 转牌计划' }).fill('根据转牌牌面和对手尺寸重新判断。');
  await page.getByRole('button', { name: '保存 Hero 推演' }).click();
  await expect(page.getByText('范围草稿：0 / 569', { exact: true })).toBeVisible();
  await expect(page.getByText('已保存到本地')).toBeVisible();
  await page.reload();
  await expect(page.getByRole('combobox', { name: 'Hero 具体组合' })).toHaveValue('AdKd');
  await expect(page.getByRole('textbox', { name: 'Hero 转牌计划' })).toHaveValue('根据转牌牌面和对手尺寸重新判断。');
  await page.getByRole('button', { name: '仅将 Hero 行动写入范围草稿' }).click();
  await expect(page.getByText('范围草稿：1 / 569', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '查看全范围模拟策略' }).click();
  const reference = page.getByTestId('reference-range');
  await expect(reference.getByRole('group', { name: '全范围推荐策略矩阵' })).toBeVisible();
  await expect(reference.getByRole('group', { name: '全范围推荐策略矩阵' }).getByRole('button')).toHaveCount(169);
  await page.getByRole('tab', { name: /参考与反馈/ }).click();
  await expect(page.getByRole('group', { name: '全范围推荐策略矩阵' })).toBeVisible();
  await expect(page.getByRole('heading', { name: /提交版本/ })).toHaveCount(0);
  await page.getByRole('tab', { name: /Hero 推演/ }).click();
  await reference.getByTestId('reference-cell-AQs').click();
  await expect(reference.getByText('AQs · 组合明细', { exact: true })).toBeVisible();
  await reference.getByTestId('reference-cell-AKs').click();
  await reference.getByRole('button', { name: '参考组合 AdKd' }).click();
  await expect(reference.getByRole('table')).toContainText('100.0%');
  await expect(page.getByText('范围草稿：1 / 569', { exact: true })).toBeVisible();
  const dismiss = page.getByRole('button', { name: '关闭提示' });
  if (await dismiss.count()) await dismiss.click();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: '.artifacts/hero/hero-1440.png', fullPage: true, animations: 'disabled' });
  await reference.screenshot({ path: '.artifacts/hero/range-reference-1440.png', animations: 'disabled' });
  await page.setViewportSize({ width: 1280, height: 1000 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: '用参考补全未填写组合', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('已经填写的 Hero 或其他组合保持不变');
  await page.getByRole('button', { name: '确认辅助补全' }).click();
  await expect(page.getByRole('tab', { name: /全范围构建/ })).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByText('当前草稿包含示例参考辅助', { exact: false })).toBeVisible();
  await expect(page.getByText(/569 \/ 569 个组合已完成/)).toBeVisible();
  await page.getByRole('button', { name: '提交策略', exact: true }).click();
  await expect(page.getByText('这份提交包含参考辅助，不等同于独立作答。')).toBeVisible();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出工作区备份' }).click();
  const download = await downloadPromise;
  const backup = JSON.parse(await readFile((await download.path())!, 'utf8'));
  const c = Object.values(backup.cases)[0] as { heroPlans: unknown[]; versions: { assistance: string }[]; draft: { choices: Record<string, { bet33: number }> } };
  expect(c.heroPlans).toHaveLength(1);
  expect(c.versions).toHaveLength(1);
  expect(c.versions[0].assistance).toBe('reference');
  expect(c.draft.choices.AdKd.bet33).toBe(10000);
  expect(errors).toEqual([]);
});

test('Hero checking moves to turn hypotheses; a changed spot cannot reuse the prior reference', async ({ page }) => {
  await page.goto('/library');
  await page.getByRole('button', { name: '创建研究案例' }).click();
  await page.getByRole('tab', { name: /Hero 推演/ }).click();
  await page.getByRole('group', { name: 'Hero 翻牌行动' }).getByRole('button', { name: '过牌', exact: true }).click();
  const branches = page.getByRole('combobox', { name: '对手后续假设' });
  await expect(branches.locator('option')).toHaveCount(2);
  await expect(branches).toContainText('转牌：BB 下注');
  await expect(branches).not.toContainText('翻牌：BB 加注');
  await page.getByRole('combobox', { name: 'Hero 后续计划' }).selectOption('call');
  await page.getByRole('button', { name: '保存 Hero 推演' }).click();
  await page.getByRole('button', { name: '扩展到 3 个同牌类组合…' }).click();
  await expect(page.getByRole('dialog')).toContainText('其他组合不变');
  await page.getByRole('button', { name: '确认扩展这 3 个组合' }).click();
  await expect(page.getByText('范围草稿：3 / 569', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '查看全范围模拟策略' }).click();
  await expect(page.getByTestId('reference-range')).toBeVisible();
  await page.getByRole('button', { name: '局面条件' }).click();
  await page.getByRole('spinbutton', { name: '底池 bb' }).fill('6.5');
  await page.getByRole('button', { name: '建立修订并清空草稿' }).click();
  await expect(page.getByTestId('reference-range')).toHaveCount(0);
  await expect(page.getByRole('button', { name: '仅将 Hero 行动写入范围草稿' })).toBeDisabled();
  await page.getByRole('button', { name: '查看全范围模拟策略' }).click();
  await expect(page.getByRole('heading', { name: '当前条件没有全范围示例参考' })).toBeVisible();
  await expect(page.getByRole('button', { name: '用参考补全未填写组合', exact: true })).toHaveCount(0);
});
